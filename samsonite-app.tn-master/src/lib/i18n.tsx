const translateDynamicText = (language: Language, value?: string | null) => {
  if (!value) return "";
  const decoded = decodeMojibake(String(value));
  if (language === "fr") return decoded;
  const normalized = normalizeDynamicKey(decoded);
  return dynamicTranslations[normalized] || decoded;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem("samsonite_language");
    return saved === "en" ? "en" : "fr";
  });

  useEffect(() => {
    localStorage.setItem("samsonite_language", language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      setLanguage: setLanguageState,
      t: (key: string) => decodeMojibake(dictionaries[language][key] || dictionaries.fr[key] || key),
      td: (value?: string | null) => translateDynamicText(language, value),
    }),
    [language]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => {
  const value = useContext(LanguageContext);
  if (!value) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }
  return value;
};
